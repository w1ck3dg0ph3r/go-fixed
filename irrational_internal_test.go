package fixed

import "testing"

func TestSqrt192(t *testing.T) {
	t.Parallel()

	cases := []struct {
		hi uint64
		lo Number
		e  Number
	}{
		{0x0, u128(0x0, 0x1), u128(0x0, 0x1)},
		{0x0, u128(0x0, 0x2), u128(0x0, 0x1)},
		{0x0, u128(0x0, 0x3), u128(0x0, 0x1)},
		{0x0, u128(0x0, 0x4), u128(0x0, 0x2)},
		{0x0, u128(0x0, 0x12), u128(0x0, 0x4)},
		{0x0, u128(0x0, 0xffffffffffffffff), u128(0x0, 0xffffffff)},
		{0x0, u128(0x1, 0x0), u128(0x0, 0x100000000)},
		{0x0, u128(0xffffffffffffffff, 0xffffffffffffffff), u128(0x0, 0xffffffffffffffff)},
		{0x1, u128(0x0, 0x0), u128(0x1, 0x0)},
		{0x28c87cb5c89a2571, u128(0xebfdcb54864ada82, 0xbf38dcfb76180000), u128(0x662dbf6a, 0x94166eb2e67dbb14)},
		{0xfffffffffffffffe, u128(0x0, 0x1), u128(0xffffffff, 0xfffffffeffffffff)},
		{0xffffffffffffffff, u128(0xffffffffffffffff, 0xffffffffffffffff), u128(0xffffffff, 0xffffffffffffffff)},
		{0xffffffffffffffff, u128(0xfffffffe00000000, 0x1), u128(0xffffffff, 0xffffffffffffffff)},
		{0xffffffffffffffff, u128(0xfffffffe00000000, 0x0), u128(0xffffffff, 0xfffffffffffffffe)},
		{0x1, u128(0x9da075a3ece216f6, 0x5ba0c5171aa1b26d), u128(0x1, 0x4567b2a99e35bf24)},
		{0x5438ddb2e1183a4, u128(0x49871f2ade00f93, 0xfc084cfc17c9e800), u128(0x24b58419, 0x4ea44634e79cf400)},
	}
	for _, tc := range cases {
		if r := sqrt192(tc.hi, tc.lo); r != tc.e {
			t.Errorf("sqrt192(%#x, %s): expected %s, got %s", tc.hi, hex(tc.lo), hex(tc.e), hex(r))
		}
	}
}
