func TestShift(t *testing.T) {
	t.Parallel()

	n := fixed.MustFromString
	cases := []struct {
		a fixed.Number
		k int
		e fixed.Number
	}{
		{n("10"), 2, n("1000")},
		{n("10"), -2, n("0.1")},
		{n("1"), 0, n("1")},
		{n("-10"), 2, n("-1000")},
		{n("-10"), -2, n("-0.1")},
		{n("0"), 5, n("0")},
		{n("0"), -5, n("0")},
		{n("1.5"), -1, n("0.15")},
		{n("2.5"), -1, n("0.25")},
		{n("-2.5"), -1, n("-0.25")},
		{n("1.23456789"), -8, n("0.0000000123456789")},
		{n("1.23456789"), -9, n("0.00000000123456789")},
		{n("999999999999999999.9999999999999999999"), 1, n("9999999999999999999.999999999999999999")},

		// Digits below the last place are discarded, towards zero on both signs.
		{n("0.0000000000000000015"), -1, n("0.0000000000000000001")},
		{n("-0.0000000000000000015"), -1, n("-0.0000000000000000001")},
		{n("0.0000000000000000001"), -1, n("0")},
		{n("3.1415926535897932384"), -20, n("0")},
		{n("9999999999999999999.9999999999999999999"), -19, n("0.9999999999999999999")},
		{n("9999999999999999999.9999999999999999999"), -37, n("0.0000000000000000009")},

		// Shifts wider than Scale, which take two steps internally.
		{n("1"), 18, n("1000000000000000000")},
		{n("0.0000000000000000001"), 19, n("1")},
		{n("0.0000000000000000001"), 20, n("10")},
		{n("0.0000000000000000001"), 37, n("1000000000000000000")},
		{n("-0.0000000000000000001"), 37, n("-1000000000000000000")},
		{n("0.9999999999999999999"), 19, n("9999999999999999999")},

		// Past Precision in either direction nothing of the value survives.
		{n("9999999999999999999.9999999999999999999"), -38, n("0")},
		{n("1"), -37, n("0")},
		{n("1"), -38, n("0")},
		{n("1"), -39, n("0")},
		{n("1"), 37, fixed.Overflow},
		{n("1"), 38, fixed.Overflow},
		{n("1"), 39, fixed.Overflow},
		{n("0.0000000000000000001"), 38, fixed.Overflow},

		{n("1"), 19, fixed.Overflow},
		{n("0.9999999999999999999"), 20, fixed.Overflow},
		{n("9999999999999999999.9999999999999999999"), 1, fixed.Overflow},

		// Results whose magnitude lands in [2^127, 2^128): wide enough to be out
		// of range, but narrow enough that the multiplication itself does not
		// overflow 128 bits.
		{n("33.2041393326771929088"), 18, fixed.Overflow},
		{n("-33.2041393326771929088"), 18, fixed.Overflow},
		{n("1701411834604692317.3168730371588410573"), 1, fixed.Overflow},
		{n("-1701411834604692317.3168730371588410573"), 1, fixed.Overflow},
		// The same, reached through the two-step path for a shift above Scale.
		{n("0.0000000000000000018"), 37, fixed.Overflow},
		{n("0.0000000000000001702"), 35, fixed.Overflow},
		// A shift above Scale whose first multiplication already overflows 128
		// bits, rather than the magnitude check catching it afterwards.
		{n("10"), 20, fixed.Overflow},
		{n("9999999999999999999.9999999999999999999"), 20, fixed.Overflow},

		{fixed.Overflow, 1, fixed.Overflow},
		{fixed.NaN, 1, fixed.NaN},
		{fixed.DivisionByZero, -1, fixed.DivisionByZero},
		{fixed.NaN, 0, fixed.NaN},
	}
	for _, tc := range cases {
		t.Run(fmt.Sprintf("Shift(%s,%d)", tc.a, tc.k), func(t *testing.T) {
			r := tc.a.Shift(tc.k)
			if r != tc.e {
				t.Errorf("expected %q, got %q", tc.e.String(), r.String())
			}
		})
	}
}

